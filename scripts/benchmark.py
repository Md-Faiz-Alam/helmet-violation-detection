"""Compare trained models: accuracy (val + test), size and CPU speed in one table.

    python scripts/benchmark.py                                   # models/best.pt + every results/train/*/weights/best.pt
    python scripts/benchmark.py --weights a.pt b.pt --device 0    # specific models, GPU for accuracy

Pick the best model by its VALIDATION columns. The test columns are the final, unbiased estimate.
"No-helmet recall" is measured at a fixed 0.25 confidence (the app's default) with IoU 0.5.
CPU latency is the mean of single-image predictions after warm-up (batch 1).
"""

import argparse
import csv
import glob
import os
import time
from datetime import date

from ultralytics import YOLO

from metrics import counts_at, load_split, predict_items, prf

VIOLATION_CLASS = "Without Helmet"


def train_args(model):
    return (getattr(model, "ckpt", None) or {}).get("train_args", {}) or {}


def train_imgsz(model, default=640):
    return int(train_args(model).get("imgsz", default))


def arch_name(model):
    name = model.model.yaml.get("yaml_file") or train_args(model).get("model") or "?"
    return os.path.splitext(os.path.basename(str(name)))[0]


def run_name(path):
    parts = os.path.normpath(path).split(os.sep)
    if len(parts) >= 3 and parts[-2] == "weights":
        return parts[-3]  # results/train/<experiment>/weights/best.pt -> <experiment>
    return "current (" + "/".join(parts[-2:]) + ")"  # e.g. models/best.pt -> current (models/best.pt)


def cpu_latency_ms(model, images, imgsz, n=30, warmup=5):
    for p in images[:warmup]:
        model.predict(p, imgsz=imgsz, device="cpu", verbose=False)
    t0 = time.perf_counter()
    for p in images[:n]:
        model.predict(p, imgsz=imgsz, device="cpu", verbose=False)
    return (time.perf_counter() - t0) / min(n, len(images)) * 1000


def evaluate(weights, data, device, conf):
    model = YOLO(weights)
    imgsz = train_imgsz(model)
    row = {
        "model": run_name(weights),
        "arch": arch_name(model),
        "imgsz": imgsz,
        "params_M": sum(p.numel() for p in model.model.parameters()) / 1e6,
        "size_MB": os.path.getsize(weights) / 1e6,
    }
    for split in ("val", "test"):
        m = model.val(data=data, split=split, imgsz=imgsz, device=device, plots=False, verbose=False)
        names, items = load_split(data, split)
        v = names.index(VIOLATION_CLASS)
        predict_items(model, items, imgsz=imgsz, device=device)
        tp, fp, fn = counts_at(items, {i: conf for i in range(len(names))}, len(names))
        row[f"{split}_mAP50"] = m.box.map50
        row[f"{split}_mAP50_95"] = m.box.map
        row[f"{split}_nohelmet_recall"] = prf(tp[v], fp[v], fn[v])[1]
        if split == "test":
            row["cpu_ms"] = cpu_latency_ms(model, [it["path"] for it in items], imgsz)
    return row


def main(args):
    weights = args.weights or (["models/best.pt"] if os.path.exists("models/best.pt") else []) + sorted(
        glob.glob("results/train/*/weights/best.pt"))
    if not weights:
        raise SystemExit("No weights found. Train a model first or pass --weights.")

    rows = []
    for w in weights:
        print(f"Benchmarking {w} ...")
        rows.append(evaluate(w, args.data, args.device, args.conf))
    rows.sort(key=lambda r: (-r["val_mAP50"]))

    os.makedirs(os.path.dirname(args.report), exist_ok=True)
    with open(args.report.replace(".md", ".csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    head = ("| Model | Arch | imgsz | Params (M) | Size (MB) | CPU ms/img | val mAP50 | val no-helmet recall "
            "| **test mAP50** | **test mAP50-95** | **test no-helmet recall** |")
    lines = [head, "|" + "---|" * 11]
    for r in rows:
        lines.append(
            f"| {r['model']} | {r['arch']} | {r['imgsz']} | {r['params_M']:.1f} | {r['size_MB']:.1f} | {r['cpu_ms']:.0f} "
            f"| {r['val_mAP50']:.3f} | {r['val_nohelmet_recall']:.3f} | {r['test_mAP50']:.3f} | {r['test_mAP50_95']:.3f} "
            f"| {r['test_nohelmet_recall']:.3f} |")
    report = f"""# Model comparison

_Generated by `scripts/benchmark.py` on {date.today()}. Sorted by validation mAP50. No-helmet recall at conf {args.conf}, IoU 0.5. CPU latency: batch 1, mean of 30 test images._

{chr(10).join(lines)}

Choose the model using the **val** columns; the **test** columns are the final, unbiased estimate.
"""
    with open(args.report, "w", encoding="utf-8") as f:
        f.write(report)
    print(report)
    print(f"Saved {args.report} (+ .csv)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Compare trained helmet models")
    ap.add_argument("--weights", nargs="*", help="Weights to compare (default: models/best.pt + results/train/*)")
    ap.add_argument("--data", default="data/data.yaml")
    ap.add_argument("--device", default=None, help="Device for accuracy evaluation; latency always uses CPU")
    ap.add_argument("--conf", type=float, default=0.25)
    ap.add_argument("--report", default="reports/model_comparison.md")
    main(ap.parse_args())
