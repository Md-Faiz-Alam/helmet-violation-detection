"""Create an oversampled training list to counter class imbalance.

The train split has ~2x more 'With Helmet' boxes than 'Without Helmet' boxes. This script
writes data/train_oversampled.txt where every image containing a 'Without Helmet' box is
repeated `--repeat` times, plus data/data_oversampled.yaml pointing at it (val/test unchanged).
Ultralytics finds each image's label by swapping /images/ for /labels/ in its path.

    python scripts/make_oversampled_split.py --repeat 2
"""

import argparse
from collections import Counter
from pathlib import Path

import yaml

from metrics import load_split

VIOLATION_CLASS = "Without Helmet"


def main(args):
    data_yaml = Path(args.data)
    cfg = yaml.safe_load(data_yaml.read_text())
    names, items = load_split(data_yaml, "train")
    v = names.index(VIOLATION_CLASS)

    lines, before, after = [], Counter(), Counter()
    for it in items:
        classes = Counter(int(c) for c in it["gt"][:, 0])
        k = args.repeat if classes[v] else 1
        lines += [it["path"]] * k
        for c, n in classes.items():
            before[c] += n
            after[c] += n * k

    out_txt = data_yaml.parent / "train_oversampled.txt"
    out_txt.write_text("\n".join(p.replace("\\", "/") for p in lines) + "\n")
    new_cfg = {**{k: cfg[k] for k in ("val", "test", "nc", "names")}, "train": out_txt.name}
    new_cfg = {"train": new_cfg.pop("train"), **new_cfg}
    out_yaml = data_yaml.parent / "data_oversampled.yaml"
    out_yaml.write_text("# Generated by scripts/make_oversampled_split.py\n" + yaml.safe_dump(new_cfg, sort_keys=False))

    print(f"Images: {len(items)} -> {len(lines)}")
    for c, name in enumerate(names):
        print(f"  {name:<15} boxes: {before[c]:>6} -> {after[c]:>6}")
    print(f"Wrote {out_txt} and {out_yaml}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Oversample images containing the violation class")
    ap.add_argument("--data", default="data/data.yaml")
    ap.add_argument("--repeat", type=int, default=2, help="How many times to include each violation image")
    main(ap.parse_args())
