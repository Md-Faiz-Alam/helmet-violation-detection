"""Choose a confidence threshold per class on the VALIDATION set, then report on the TEST set.

Why: the app used one global threshold (0.25). Missing a rider without a helmet costs more
than a false alarm, so for "Without Helmet" we maximise F2 (recall weighted 2x) instead of F1.
By default only the violation class is tuned; other classes keep --default_conf (tuning
"With Helmet" for F1 on our small val set raised its threshold to 0.58 and hid correct
detections without improving test F1). Use --tune_all to tune every class.
Thresholds are tuned on val only, so the test numbers stay an honest estimate.

    python scripts/tune_thresholds.py --weights models/best.pt
"""

import argparse
import os
from datetime import date

import numpy as np
import yaml
from ultralytics import YOLO

from metrics import counts_at, load_split, predict_items, prf

VIOLATION_CLASS = "Without Helmet"


def sweep(items, n_classes, cls, betas, grid, base_thresholds):
    """Best threshold for one class (matching is class-aware, so classes can be tuned independently)."""
    best = (None, -1.0)
    for t in grid:
        thr = dict(base_thresholds)
        thr[cls] = t
        tp, fp, fn = counts_at(items, thr, n_classes)
        _, _, f = prf(tp[cls], fp[cls], fn[cls], beta=betas[cls])
        if f > best[1] + 1e-9:
            best = (float(t), f)
    return best


def table(items, names, thresholds, betas):
    tp, fp, fn = counts_at(items, thresholds, len(names))
    rows = []
    for c, name in enumerate(names):
        p, r, f = prf(tp[c], fp[c], fn[c], beta=betas[c])
        rows.append((name, thresholds[c], p, r, f, int(tp[c]), int(fp[c]), int(fn[c])))
    return rows


def fmt(rows, betas):
    out = ["| Class | Threshold | Precision | Recall | F-score | TP | FP | FN |", "|---|---|---|---|---|---|---|---|"]
    for (name, t, p, r, f, tp, fp, fn), b in zip(rows, betas, strict=True):
        out.append(f"| {name} | {t:.2f} | {p:.3f} | {r:.3f} | {f:.3f} (F{b:g}) | {tp} | {fp} | {fn} |")
    return "\n".join(out)


def main(args):
    model = YOLO(args.weights)
    names, val_items = load_split(args.data, "val")
    _, test_items = load_split(args.data, "test")
    n = len(names)
    betas = [args.violation_beta if name == VIOLATION_CLASS else 1.0 for name in names]

    print(f"Predicting {len(val_items)} val + {len(test_items)} test images...")
    predict_items(model, val_items, imgsz=args.img, device=args.device)
    predict_items(model, test_items, imgsz=args.img, device=args.device)

    grid = np.round(np.arange(0.05, 0.91, 0.01), 2)
    default = {c: args.default_conf for c in range(n)}
    tuned = dict(default)
    for c in range(n):
        if args.tune_all or names[c] == VIOLATION_CLASS:
            tuned[c], _ = sweep(val_items, n, c, betas, grid, default)

    sections = []
    for split, items in (("Validation (used for tuning)", val_items), ("Test (held out)", test_items)):
        sections.append(f"### {split}\n\n**Default ({args.default_conf} for all classes)**\n\n"
                        f"{fmt(table(items, names, default, betas), betas)}\n\n"
                        f"**Tuned per-class thresholds**\n\n{fmt(table(items, names, tuned, betas), betas)}\n")

    report = f"""# Per-class confidence thresholds

_Generated by `scripts/tune_thresholds.py` on {date.today()} · weights: `{args.weights}` · IoU 0.5_

Objective: F{args.violation_beta:g} for **{VIOLATION_CLASS}** (missing a violator costs more than a false alarm). {"Other classes: F1." if args.tune_all else f"Other classes keep the default {args.default_conf}."}
Thresholds are chosen on the validation set only; the test set is used once, for reporting.

**Chosen thresholds:** {", ".join(f"{names[c]} = {tuned[c]:.2f}" for c in range(n))}

{chr(10).join(sections)}
Note: precision/recall here are at a fixed operating threshold, so they differ from the
max-F1 summary that `evaluate.py` (Ultralytics val) prints. mAP is threshold-independent and unchanged.
"""
    os.makedirs(os.path.dirname(args.report), exist_ok=True)
    with open(args.report, "w", encoding="utf-8") as f:
        f.write(report)

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("# Per-class confidence thresholds (generated by scripts/tune_thresholds.py)\n")
        f.write(f"# weights: {args.weights}\n")
        yaml.safe_dump({"thresholds": {names[c]: tuned[c] for c in range(n)}}, f, sort_keys=False)

    print(report)
    print(f"Saved thresholds to {args.out} and report to {args.report}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Tune per-class confidence thresholds")
    ap.add_argument("--weights", default="models/best.pt")
    ap.add_argument("--data", default="data/data.yaml")
    ap.add_argument("--img", type=int, default=640)
    ap.add_argument("--device", default=None)
    ap.add_argument("--default_conf", type=float, default=0.25, help="Baseline single threshold to compare against")
    ap.add_argument("--violation_beta", type=float, default=2.0, help="F-beta for the violation class (2 = recall x2)")
    ap.add_argument("--tune_all", action="store_true", help="Also tune non-violation classes (F1)")
    ap.add_argument("--out", default="configs/thresholds.yaml")
    ap.add_argument("--report", default="reports/thresholds.md")
    main(ap.parse_args())
