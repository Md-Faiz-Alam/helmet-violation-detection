"""Dataset audit: what is actually in each split, and does performance depend on it?

Uses a COCO-pretrained YOLO model to tag every image as motorcycle / bicycle / neither, then:
  1. reports the composition of train / valid / test (train is de-duplicated by source filename,
     since Roboflow stored several augmented copies of each original; a few originals share a filename)
  2. reports helmet-model recall separately for motorcycle and bicycle images (val + test)

    python scripts/dataset_audit.py
"""

import argparse
import os
import re
from collections import Counter, defaultdict
from datetime import date

import yaml
from ultralytics import YOLO

from metrics import counts_at, load_split, predict_items, prf

VEHICLES = ("motorcycle", "bicycle", "neither")


def source_name(path):
    """'BikesHelmets108_png_jpg.rf.<hash>.jpg' -> 'BikesHelmets108' (all augmented copies share it)."""
    name = os.path.basename(path)
    return re.split(r"_png_jpg|_jpg\.rf\.|\.rf\.", name)[0]


def tag_vehicle(coco_model, path, conf, device):
    r = coco_model.predict(path, conf=conf, device=device, verbose=False)[0]
    found = {r.names[int(c)] for c in r.boxes.cls}
    return "motorcycle" if "motorcycle" in found else "bicycle" if "bicycle" in found else "neither"


def main(args):
    coco = YOLO(args.coco_weights)
    helmet = YOLO(args.weights)
    thr_cfg = yaml.safe_load(open(args.thresholds, encoding="utf-8"))["thresholds"] if os.path.exists(args.thresholds) else None

    comp_rows = ["| Split | Images (train: one per source filename) | Motorcycle | Bicycle | Neither |", "|---|---|---|---|---|"]
    perf_rows = ["| Split | Vehicle | Images | " + "Recall {} | " * 2 + "", "|---|---|---|---|---|"]
    for split in ("train", "val", "test"):
        names, items = load_split(args.data, split)
        if split == "train":  # one image per source filename (augmented copies share it)
            unique = {}
            for it in items:
                unique.setdefault(source_name(it["path"]), it)
            items = list(unique.values())
        print(f"Tagging {len(items)} {split} images...")
        for it in items:
            it["vehicle"] = tag_vehicle(coco, it["path"], args.coco_conf, args.device)
        c = Counter(it["vehicle"] for it in items)
        n = len(items)
        comp_rows.append(f"| {split} | {n} | " + " | ".join(f"{c[v]} ({c[v] / n:.0%})" for v in VEHICLES) + " |")

        if split in ("val", "test"):
            thresholds = {i: float(thr_cfg[nm]) for i, nm in enumerate(names)} if thr_cfg else {i: 0.25 for i in range(len(names))}
            predict_items(helmet, items, imgsz=args.img, device=args.device)
            groups = defaultdict(list)
            for it in items:
                groups[it["vehicle"]].append(it)
            perf_rows[0] = "| Split | Vehicle | Images | " + " | ".join(f"Recall {nm}" for nm in names) + " |"
            for v in VEHICLES:
                if not groups[v]:
                    continue
                tp, fp, fn = counts_at(groups[v], thresholds, len(names))
                recalls = [f"{prf(tp[k], fp[k], fn[k])[1]:.2f} ({tp[k] + fn[k]} obj)" for k in range(len(names))]
                perf_rows.append(f"| {split} | {v} | {len(groups[v])} | " + " | ".join(recalls) + " |")

    thr_txt = ", ".join(f"{k} = {v}" for k, v in thr_cfg.items()) if thr_cfg else "0.25 for all classes"
    report = f"""# Dataset audit

_Generated by `scripts/dataset_audit.py` on {date.today()} · vehicle tagger: `{args.coco_weights}` (COCO, conf {args.coco_conf}) · helmet weights: `{args.weights}` · thresholds: {thr_txt}_

An image is tagged **motorcycle** if the COCO model finds a motorcycle in it, otherwise **bicycle** if it finds a bicycle, otherwise **neither**. The tagger is automatic, so expect a few mistakes.

## Split composition

{chr(10).join(comp_rows)}

## Helmet-model recall by vehicle type

{chr(10).join(perf_rows)}

Small groups give noisy numbers, so compare trends rather than exact values.
"""
    os.makedirs(os.path.dirname(args.report), exist_ok=True)
    with open(args.report, "w", encoding="utf-8") as f:
        f.write(report)
    print(report)
    print(f"Report: {args.report}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Audit dataset composition by vehicle type")
    ap.add_argument("--weights", default="models/best.pt")
    ap.add_argument("--data", default="data/data.yaml")
    ap.add_argument("--thresholds", default="configs/thresholds.yaml")
    ap.add_argument("--coco_weights", default="yolo26s.pt", help="COCO-pretrained model used to tag vehicles")
    ap.add_argument("--coco_conf", type=float, default=0.35)
    ap.add_argument("--img", type=int, default=640)
    ap.add_argument("--device", default=None)
    ap.add_argument("--report", default="reports/dataset_audit.md")
    main(ap.parse_args())
